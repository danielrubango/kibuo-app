# Generates lib/domain/money/currency_catalog.dart from Unicode CLDR.
# Usage, in a Python virtual environment with Babel (pip install babel):
#   python tool/gen_currencies.py lib/domain/money/currency_catalog.dart
import sys
from babel import Locale
from babel.numbers import list_currencies, get_currency_precision, get_territory_currencies
from babel.core import get_global
out = sys.argv[1]
fr, en = Locale('fr'), Locale('en')
skip = {'XAG','XAU','XBA','XBB','XBC','XBD','XDR','XPD','XPT','XSU','XTS','XUA','XXX','BOV','CHE','CHW','CLF','COU','MXV','USN','UYI','UYW','VED','XSU','ZWL','SLL','CUC','HRK','SVC'}
import datetime
today = datetime.date.today()
current = set()
for t in get_global('territory_currencies'):
    current.update(get_territory_currencies(t, start_date=today, tender=True))
codes = sorted(c for c in current if c not in skip and fr.currencies.get(c) and en.currencies.get(c))
# Symbols people use day to day, where CLDR's are too formal.
symbols = {'CDF':'FC','USD':'$','EUR':'€','XAF':'FCFA','XOF':'F CFA','RWF':'FRw','BIF':'FBu','UGX':'USh','KES':'Ksh','TZS':'TSh','ZMW':'K','AOA':'Kz','ZAR':'R','NGN':'₦','GHS':'GH₵','GBP':'£','CAD':'CA$','CHF':'CHF','CNY':'¥','JPY':'¥','AED':'AED','INR':'₹','MAD':'DH','EGP':'E£','ETB':'Br','MZN':'MT','MWK':'MK','SSP':'SSP','SDG':'SDG','XPF':'F CFP','HTG':'G','BRL':'R$','MGA':'Ar','DZD':'DA','TND':'DT'}
# Fractional units not used in practice.
no_decimals = {'CDF','XAF','XOF','TZS','MGA','XPF'}
def esc(s): return s.replace("\\","\\\\").replace("'","\\'").replace('$','\\$')
def cap(s): return s[:1].upper()+s[1:]
lines = []
for c in codes:
    sym = symbols.get(c) or en.currency_symbols.get(c, c)
    if c not in symbols and len(sym) > 4 and sym != c: sym = c
    digits = get_currency_precision(c)
    dec = digits > 0 and c not in no_decimals
    lines.append("  CurrencyInfo('%s', digits: %d, usesDecimals: %s, symbol: '%s', nameFr: '%s', nameEn: '%s')," % (c, digits, 'true' if dec else 'false', esc(sym), esc(cap(fr.currencies[c])), esc(en.currencies[c])))
# Main current currency of each country.
terr = {}
for t in get_global('territory_currencies'):
    cur = get_territory_currencies(t, start_date=today, tender=True)
    if cur and cur[0] in codes: terr[t] = cur[0]
tl = ', '.join("'%s': '%s'" % (k, v) for k, v in sorted(terr.items()))
dart = '''// GENERATED by scratchpad gen_currencies.py from Unicode CLDR (Babel %s).
// Do not edit by hand; regenerate to update names or add currencies.
// ignore_for_file: lines_longer_than_80_chars
import 'package:kibuo/domain/money/currency.dart';

/// Every currency in current use, by ISO 4217 code.
const currencyCatalog = <CurrencyInfo>[
%s
];

/// The main currency of each country (ISO 3166 code), to suggest the
/// phone's own currency first.
const countryCurrency = <String, String>{%s};
''' % (__import__('babel').__version__, '\n'.join(lines), tl)
open(out,'w').write(dart)
print(len(codes), 'currencies,', len(terr), 'countries')
